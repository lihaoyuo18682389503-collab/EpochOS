def glyph_to_bytes(proto):
    """将 6x12 原型映射为 16 字节 (8x16): 左/右各 1px, 上/下各 2px。"""
    out = []
    # 顶部 2 行空白
    out.append(0x00)
    out.append(0x00)
    for row in proto:
        byte = 0
        # 左侧 1px 空白
        for c, ch in enumerate(row):
            if ch == '#':
                byte |= (1 << (7 - (c + 1)))
        out.append(byte)
    # 底部 2 行空白
    out.append(0x00)
    out.append(0x00)
    return out


def main():
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "kernel", "font8x16.h")
    out_path = os.path.abspath(out_path)

    # 校验字符集完整性
    missing = [chr(c) for c in range(0x20, 0x7F) if chr(c) not in F]
    if missing:
        raise SystemExit(f"missing glyphs: {missing}")

    lines = []
    lines.append("// ============================================================")
    lines.append("// EpochOS 自研点阵字体 (ASCII 0x20-0x7E, 8x16)")
    lines.append("// 设计: 6x12 原型映射到 8x16, 圆润加粗, 护眼易读")
    lines.append("// 生成工具: tools/generate_font.py (python tools/generate_font.py)")
    lines.append("// 每字符 16 行, 每行 1 字节, MSB 为最左像素")
    lines.append("// ============================================================")
    lines.append("#ifndef EPOCHOS_FONT8X16_H")
    lines.append("#define EPOCHOS_FONT8X16_H")
    lines.append("#include \"types.h\"")
    lines.append("")
    lines.append("static const uint8_t font8x16[95][16] = {")

    for code in range(0x20, 0x7F):
        ch = chr(code)
        glyph = glyph_to_bytes(F[ch])
        row_str = ", ".join("0x%02X" % b for b in glyph)
        lines.append("    { %s }," % row_str)

    lines.append("};")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"font8x16.h generated: {out_path} ({len(lines)} lines)")
    # 简单自检
    for ch, proto in F.items():
        if len(proto) != 12 or any(len(r) != 6 for r in proto):
            raise SystemExit(f"bad glyph size for {ch!r}")


if __name__ == "__main__":
    main()
